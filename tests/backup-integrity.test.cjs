"use strict";
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root=path.resolve(__dirname,'..');
const raw=fs.readFileSync(path.join(root,'backups/gym-tracker-backup-2026-11-25-originale.json'));
assert.equal(crypto.createHash('sha256').update(raw).digest('hex'),'c0cb56e3ee7dd6ccf2352d00c1b2a917123f00e9ce095af0dfe94b91b5f05846');
const backup=JSON.parse(raw.toString('utf8'));
assert.equal(backup.type,'gym-tracker-backup');
const context={};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'history_seed.js'),'utf8')+'\n'+
  'globalThis.extracted={history:INITIAL_HISTORY,bootstrap:INITIAL_BOOTSTRAP};',context);
const embedded=JSON.parse(JSON.stringify(context.extracted));
const expected=JSON.parse(JSON.stringify(backup.state));
const snapshotHistory=expected.history;delete expected.history;expected.version='9.5.1';
assert.deepStrictEqual(embedded.history,snapshotHistory);
assert.deepStrictEqual(embedded.bootstrap,expected);
assert.equal(embedded.history.length,52);
assert.equal(new Set(embedded.history.map(x=>x.id)).size,52);
assert.equal(embedded.bootstrap.currentWeek,3);
assert.equal(embedded.bootstrap.currentSession,null);
assert.equal(embedded.bootstrap.programLibrary.length,1);
assert.equal(embedded.bootstrap.gymProfiles.length,5);
assert.equal(Object.keys(embedded.bootstrap.exerciseCatalog).length,140);
const imported=JSON.parse(fs.readFileSync(path.join(root,'backups/gym-tracker-backup-2026-11-25-v951-importabile.json'),'utf8'));
assert.deepStrictEqual(imported.state,{...backup.state,version:'9.5.1'});
